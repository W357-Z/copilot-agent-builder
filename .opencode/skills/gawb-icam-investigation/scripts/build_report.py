"""build_report.py - fill the controlled GAWB WHS-TMP-0207 template with
investigation data and skill-rendered charts, producing the final report DOCX.

Usage:
    python build_report.py <data.json> <charts_dir> <out.docx> [audit]

The template is copied byte-exact from the package assets and filled in place:
SDT content controls are filled positionally by heading scope, repeating
table rows (CAP, Photos, Appendices, Team, Approval) are unwrapped from their
repeating-section wrappers, cloned per data item and filled cell-wise. Charts
(PNG, generated by render_charts.py) are embedded after their section anchors.

Pass "audit" as the 4th argument to print a fill audit instead of exiting
quietly. Exit codes: 0 ok, 2 usage, 3 data error, 1 unexpected.
Stdlib only; no network.
"""
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib_docx as L  # noqa: E402

W = L.WNS  # braced WordprocessingML namespace for ElementTree paths

TEMPLATE = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        os.pardir, "assets", "templates",
                        "Incident Investigation Report.dotx")

CHART_ANCHORS = {  # section heading -> (chart filename, caption)
}


# ------------------------------------------------------------ structure ----
def unwrap_repeaters(tbl):
    """Replace direct-child SDT wrappers of a table with their inner content.

    Repeating sections in this template wrap data rows as
    sdt(repeatingSection) > sdtContent > sdt(repeatingSectionItem)
    > sdtContent > tr. Unwrapping yields plain tr children, one per data row.
    """
    changed = True
    while changed:
        changed = False
        for sdt in list(tbl):
            if sdt.tag != W + "sdt":
                continue
            cont = sdt.find(W + "sdtContent")
            if cont is None:
                continue
            idx = list(tbl).index(sdt)
            inner = list(cont)
            tbl.remove(sdt)
            for i, el in enumerate(inner):
                tbl.insert(idx + i, el)
            changed = True


def heading_scopes(doc):
    """Ordered [(heading_text, [elements...])] between consecutive headings.

    Elements before the first heading are grouped under "".
    """
    body = doc.find(W + "body")
    scopes = []
    cur_name, cur_items = "", []
    for child in list(body):
        if child.tag == W + "sectPr":
            continue
        style = ""
        pr = child.find(W + "pPr") if child.tag == W + "p" else None
        if pr is not None:
            st = pr.find(W + "pStyle")
            if st is not None:
                style = st.get(W + "val", "")
        text = "".join(t.text or "" for t in child.iter(W + "t")).strip() \
            if child.tag == W + "p" else ""
        if child.tag == W + "p" and style.lower().startswith(
                ("heading", "titre")) and text:
            scopes.append((cur_name, cur_items))
            cur_name, cur_items = text, []
        else:
            cur_items.append(child)
    scopes.append((cur_name, cur_items))
    return scopes


def scope_map(doc):
    m = {}
    for name, items in heading_scopes(doc):
        m.setdefault(name, []).extend(items)
    return m


def scope_sdts(items):
    out = []
    for el in items:
        out.extend([s for s in el.iter(W + "sdt")])
    return out


def effective_cells(tr):
    cells = []
    for ch in tr:
        if ch.tag == W + "tc":
            cells.append(ch)
        elif ch.tag == W + "sdt":
            cont = ch.find(W + "sdtContent")
            if cont is not None:
                cells.extend([c for c in list(cont) if c.tag == W + "tc"])
    return cells


def clone_row(tbl, template_row):
    new_r = L._deepcopy(template_row)
    idx = list(tbl).index(template_row)
    tbl.insert(idx + 1, new_r)
    return new_r


def fill_cell(cell, value, kind="text"):
    sdts = list(cell.iter(W + "sdt"))
    if sdts:
        L.fill_sdt(sdts[0], value)
        return
    pars = cell.findall(W + "p")
    if not pars:
        pars = [ET.SubElement(cell, W + "p")]
    L.fill_plain_paragraph(pars[0], value)


# ------------------------------------------------------------ chart embed --
def insert_image_paragraph(body, anchor, parts, png_path, doc_id, caption,
                           width_cm=16.0):
    rid, name, cx, cy = L.add_png(parts, png_path, width_cm=width_cm)
    xml = (L.DRAWING_XML.replace("{cx}", str(cx)).replace("{cy}", str(cy))
           .replace("{id}", str(doc_id)).replace("{name}", L.esc(name))
           .replace("{rid}", rid))
    p = ET.Element(W + "p")
    ppr = ET.SubElement(p, W + "pPr")
    jc = ET.SubElement(ppr, W + "jc")
    jc.set(W + "val", "center")
    run = ET.SubElement(p, W + "r")
    run.append(ET.fromstring(xml))
    parent = body
    idx = list(parent).index(anchor)
    parent.insert(idx + 1, p)
    last = p
    if caption:
        cap_p = ET.Element(W + "p")
        cppr = ET.SubElement(cap_p, W + "pPr")
        jc2 = ET.SubElement(cppr, W + "jc")
        jc2.set(W + "val", "center")
        r = ET.SubElement(cap_p, W + "r")
        rpr = ET.SubElement(r, W + "rPr")
        i = ET.SubElement(rpr, W + "i")
        c = ET.SubElement(rpr, W + "color")
        c.set(W + "val", L.BRAND_GREY)
        sz = ET.SubElement(rpr, W + "sz")
        sz.set(W + "val", "16")
        t = ET.SubElement(r, W + "t")
        t.text = caption
        parent.insert(list(parent).index(last) + 1, cap_p)
        last = cap_p
    return doc_id + 1


def embed_png_in_sdt(sdt, parts, png_path, doc_id, width_cm=7.5):
    """Put an inline picture into a cell-wrapping SDT (photo placeholder)."""
    cont = sdt.find(W + "sdtContent")
    if cont is None:
        return doc_id
    rid, name, cx, cy = L.add_png(parts, png_path, width_cm=width_cm)
    xml = (L.DRAWING_XML.replace("{cx}", str(cx)).replace("{cy}", str(cy))
           .replace("{id}", str(doc_id)).replace("{name}", L.esc(name))
           .replace("{rid}", rid))
    # clear existing paragraphs in the deepest tc (if any)
    tcs = [c for c in list(cont) if c.tag == W + "tc"]
    target = tcs[0] if tcs else cont
    for p in list(target):
        if p.tag == W + "p":
            target.remove(p)
    p = ET.SubElement(target, W + "p")
    ppr = ET.SubElement(p, W + "pPr")
    jc = ET.SubElement(ppr, W + "jc")
    jc.set(W + "val", "center")
    run = ET.SubElement(p, W + "r")
    run.append(ET.fromstring(xml))
    return doc_id + 1


# ---------------------------------------------------------------- helpers --
def fmt_factors(flist):
    lines = []
    for f in flist or []:
        code = f.get("code", "")
        text = f.get("text", "")
        reason = f.get("reason", "")
        rating = f.get("rating", "")
        line = "%s %s" % (code, text) if code else text
        if rating:
            line += " (rating: %s)" % rating
        if reason:
            line += " - reason: %s" % reason
        lines.append(line)
    return lines


def multi_lines(values, numbered=True):
    out = []
    for i, v in enumerate(values or [], 1):
        if isinstance(v, dict):
            v = v.get("text", "")
        v = (v or "").strip()
        if not v:
            continue
        out.append(("%d. %s" % (i, v)) if numbered else v)
    return out


# ------------------------------------------------------------------ main ---
def main(argv):
    if len(argv) < 3 or len(argv) > 4:
        sys.stderr.write(__doc__)
        return 2
    data_path, charts_dir, out_path = argv[0], argv[1], argv[2]
    audit = len(argv) == 4 and argv[3] == "audit"

    if not os.path.isfile(TEMPLATE):
        sys.stderr.write("build_report: template missing: %s\n" % TEMPLATE)
        return 3
    try:
        with open(data_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except OSError as e:
        sys.stderr.write("build_report: cannot read data file: %s\n" % e)
        return 3
    except ValueError as e:
        sys.stderr.write("build_report: data file is not valid JSON: %s\n" % e)
        return 3

    inc = data.get("incident") if isinstance(data.get("incident"), dict) else {}
    meta = data.get("meta") if isinstance(data.get("meta"), dict) else {}
    factors = data.get("factors") if isinstance(data.get("factors"), dict) else {}

    filled, missing = [], []

    def need(path, value):
        if value:
            filled.append(path)
            return str(value)
        missing.append(path)
        return None

    parts = L.load_parts(TEMPLATE)
    original_doc_bytes = parts["word/document.xml"]
    # A .docx container must declare the document content type; the template
    # ships as .dotx (template.main). Word refuses the mixed declaration.
    ct = parts["[Content_Types].xml"].decode("utf-8")
    ct = ct.replace("wordprocessingml.template.main+xml",
                    "wordprocessingml.document.main+xml")
    parts["[Content_Types].xml"] = ct.encode("utf-8")
    doc = L.parse_xml(parts["word/document.xml"])
    body = doc.find(W + "body")
    scopes = scope_map(doc)
    doc_id = 100

    def grab(scope_name):
        items = scopes.get(scope_name, [])
        if not items:
            return None
        return items

    # ---- repeating tables: unwrap first (before any scope SDT capture) ----
    tail_tables = {}
    for key, snips in [("cap", ["Recommendation", "Responsible Dept"]),
                       ("photos", None), ("appendices", ["Appendix ID"]),
                       ("team", ["Name of Investigator"]),
                       ("approval", ["Name of Lead Investigator"])]:
        if snips is None:
            tbl = None
            for t in doc.iter(W + "tbl"):
                if "Revision" in "".join(x.text or "" for x in t.iter(W + "t")):
                    continue
                has_desc = any("Description" in "".join(
                    x.text or "" for x in sdt.iter(W + "t"))
                    for sdt in t.iter(W + "sdt"))
                if has_desc:
                    tbl = t
                    break
        else:
            tbl = L.find_table(doc, snips)
        if tbl is not None:
            unwrap_repeaters(tbl)
        tail_tables[key] = tbl

    # recompute scopes after unwrap (document changed)
    scopes = scope_map(doc)

    # ---- incident details table ----
    items = grab("Incident Details")
    if items:
        s = scope_sdts(items)
        vals = [
            ("incident.title", inc.get("title")),
            ("incident.type", inc.get("type")),
            ("incident.date", inc.get("date")),
            ("incident.inx_ref", inc.get("inx_ref")),
            ("incident.risk_actual", inc.get("risk_actual")),
            ("incident.risk_potential", inc.get("risk_potential")),
            ("incident.involved_parties", inc.get("involved_parties")),
            ("incident.building", inc.get("building")),
            ("incident.location", inc.get("location")),
            ("incident.activity_type", inc.get("activity_type")),
            ("incident.risk_assessment", inc.get("risk_assessment")),
        ]
        for i, (path, value) in enumerate(vals):
            if i < len(s):
                v = need(path, value)
                if v is not None:
                    L.fill_sdt(s[i], v)
        # checkboxes: Yes / No
        if len(s) > 13:
            std = (inc.get("standard_controls") or "").strip().lower()
            if std in ("yes", "no"):
                L.set_checkbox(s[11], std == "yes")
                L.set_checkbox(s[12], std == "no")
                filled.append("incident.standard_controls")
            else:
                missing.append("incident.standard_controls")
        if len(s) > 13:
            v = need("incident.standard_ref", inc.get("standard_ref"))
            if v is not None:
                L.fill_sdt(s[13], v)

    # ---- simple section fills ----
    simple = [
        ("3.1Assumptions and Exclusions (When Applicable)",
         [("assumptions", data.get("assumptions"))], False),
        ("Incident Description", [("incident.description",
                                   inc.get("description"))], False),
        ("4.2Details of Injury / Damage / Impact",
         [("incident.injuries", inc.get("injuries"))], False),
        ("Immediate Actions Taken by Management Following the Event",
         [("incident.immediate_actions", inc.get("immediate_actions"))], False),
        ("Basic Causes", [("basic_cause", data.get("basic_cause"))], False),
        ("Absent / Failed Defences",
         [("factors.absent_failed", fmt_factors(factors.get("absent_failed")))],
         True),
        ("Individual / Team Actions",
         [("factors.individual_team",
           fmt_factors(factors.get("individual_team")))], True),
        ("Task / Environment Conditions",
         [("factors.task_env", fmt_factors(factors.get("task_env")))], True),
        ("Organisational Factors",
         [("factors.organisational",
           fmt_factors(factors.get("organisational")))], True),
        ("Conclusions and Observations",
         [("conclusions", data.get("conclusions"))], False),
        ("Recommendations",
         [("recommendations",
           multi_lines(data.get("recommendations"), numbered=False))],
         True),
        ("Significant Learnings",
         [("learnings", multi_lines(data.get("learnings"), numbered=False))],
         True),
        ("Analysis of Contributing Factors (PEEPO)",
         [("peepo_note", data.get("peepo_note"))], False),
        ("Timeline Chart and 5-Whys",
         [("timeline_note", data.get("timeline_note"))], False),
    ]
    for scope_name, pairs, force_multi in simple:
        items = grab(scope_name)
        if not items:
            missing.append("scope:%s" % scope_name)
            continue
        s = scope_sdts(items)
        for j, (path, value) in enumerate(pairs):
            if j < len(s):
                if isinstance(value, list):
                    v = value
                    if v:
                        filled.append(path)
                    else:
                        missing.append(path)
                    if v:
                        L.fill_sdt(s[j], v, multi=True)
                else:
                    v = need(path, value)
                    if v is not None:
                        L.fill_sdt(s[j], v, multi=force_multi)

    # ---- recommendations & learnings with fallbacks ----
    if "recommendations" in missing:
        items = grab("Recommendations")
        if items:
            s = scope_sdts(items)
            recs = multi_lines([r.get("text") for r in
                                data.get("recommendations", [])],
                               numbered=False)
            if recs:
                L.fill_sdt(s[0], recs, multi=True)
                missing.remove("recommendations")
                filled.append("recommendations")
    if "learnings" in missing:
        items = grab("Significant Learnings")
        if items:
            s = scope_sdts(items)
            lrn = multi_lines(data.get("learnings"), numbered=False)
            if lrn:
                L.fill_sdt(s[0], lrn, multi=True)
                missing.remove("learnings")
                filled.append("learnings")

    # ---- PEEPO / timeline note fallbacks from chart presence ----
    if "peepo_note" in missing:
        items = grab("Analysis of Contributing Factors (PEEPO)")
        if items:
            s = scope_sdts(items)
            L.fill_sdt(s[0], "See PEEPO analysis chart below and Appendix C "
                             "worksheet (attached).", multi=False)
            missing.remove("peepo_note")
            filled.append("peepo_note(auto)")
    if "timeline_note" in missing:
        items = grab("Timeline Chart and 5-Whys")
        if items:
            s = scope_sdts(items)
            L.fill_sdt(s[0], "See timeline chart and 5-Whys chart below; "
                             "copies attached to Section 13.", multi=False)
            missing.remove("timeline_note")
            filled.append("timeline_note(auto)")

    # ---- chart embedding ----
    def chart_png(name):
        p = os.path.join(charts_dir, name)
        return p if os.path.isfile(p) else None

    def anchor_sdt(scope_name, index=0):
        items = grab(scope_name)
        if not items:
            return None
        s = scope_sdts(items)
        return s[index] if index < len(s) else None

    for scope_name, png_name, caption in [
            ("Organisational Factors", "icam-chart.png",
             "ICAM Analysis Chart - contributing factors"),
            ("Analysis of Contributing Factors (PEEPO)", "peepo-chart.png",
             "PEEPO analysis chart"),
            ("Timeline Chart and 5-Whys", "icam-timeline.png",
             "Incident timeline chart"),
            ("Timeline Chart and 5-Whys", "icam-5whys.png",
             "5-Whys analysis chart")]:
        png = chart_png(png_name)
        if not png:
            missing.append("chart:%s" % png_name)
            continue
        anchor = anchor_sdt(scope_name)
        if anchor is not None:
            parent = body if anchor in list(body) else None
            if parent is None:
                # find the anchor's top-level ancestor in body
                pm = {c: p for p in body.iter() for c in p}
                top = anchor
                while pm.get(top) is not None and pm[top] is not body:
                    top = pm[top]
                parent, anchor_el = body, top
            else:
                anchor_el = anchor
            doc_id = insert_image_paragraph(body, anchor_el, parts, png,
                                            doc_id, caption)
            filled.append("chart:%s" % png_name)

    # ---- CAP table ----
    tbl = tail_tables.get("cap")
    cap_rows = data.get("cap") if isinstance(data.get("cap"), list) else []
    if tbl is not None and cap_rows:
        trs = tbl.findall(W + "tr")
        if len(trs) >= 2:
            template_row = trs[-1]
            for extra in trs[2:-1]:
                tbl.remove(extra)
            row = template_row
            for item in cap_rows:
                cells = effective_cells(row)
                if len(cells) >= 4:
                    fill_cell(cells[0], item.get("recommendation", ""))
                    fill_cell(cells[1], item.get("dept", ""))
                    fill_cell(cells[2], item.get("person", ""))
                    fill_cell(cells[3], item.get("due", ""))
                filled.append("cap.row")
                if item is not cap_rows[-1]:
                    row = clone_row(tbl, row)
    elif cap_rows:
        missing.append("cap.table")

    # ---- Photos ----
    tbl = tail_tables.get("photos")
    photos = data.get("photos") if isinstance(data.get("photos"), list) else []
    if tbl is not None and photos:
        trs = [r for r in tbl.findall(W + "tr") if effective_cells(r)]
        template_row = trs[-1] if trs else None
        if template_row is not None:
            for extra in trs[1:-1]:
                tbl.remove(extra)
            row = template_row
            for start in range(0, len(photos), 2):
                pair = photos[start:start + 2]
                cells = effective_cells(row)
                for ci, photo in enumerate(pair):
                    if ci >= len(cells):
                        break
                    cell = cells[ci]
                    cell_sdts = list(cell.iter(W + "sdt"))
                    img_sdt = cell_sdts[0] if cell_sdts else None
                    desc_sdt = cell_sdts[1] if len(cell_sdts) > 1 else None
                    if desc_sdt is not None:
                        L.fill_sdt(desc_sdt, photo.get("description", ""))
                    img_path = photo.get("image") or ""
                    if img_sdt is not None and img_path and \
                            os.path.isfile(img_path):
                        doc_id = embed_png_in_sdt(img_sdt, parts, img_path,
                                                  doc_id)
                filled.append("photos.row")
                if start + 2 < len(photos):
                    row = clone_row(tbl, row)
    elif photos:
        missing.append("photos.table")

    # ---- Appendices ----
    tbl = tail_tables.get("appendices")
    appx = data.get("appendices") if isinstance(data.get("appendices"),
                                                list) else []
    if tbl is not None and appx:
        trs = tbl.findall(W + "tr")
        template_row = trs[-1] if len(trs) >= 2 else None
        if template_row is not None:
            for extra in trs[2:-1]:
                tbl.remove(extra)
            row = template_row
            for item in appx:
                cells = effective_cells(row)
                if len(cells) >= 5:
                    fill_cell(cells[0], item.get("id", ""))
                    fill_cell(cells[1], item.get("name", ""))
                    fill_cell(cells[2], item.get("reference", ""))
                    fill_cell(cells[3], item.get("date", ""))
                    fill_cell(cells[4], item.get("type", ""))
                filled.append("appendices.row")
                if item is not appx[-1]:
                    row = clone_row(tbl, row)
    elif appx:
        missing.append("appendices.table")

    # ---- Investigation Team / Approval ----
    team_rows = data.get("team_members") if isinstance(
        data.get("team_members"), list) else []
    for key, rows_data in [("team", team_rows),
                           ("approval", team_rows[:1])]:
        tbl = tail_tables.get(key)
        if tbl is None:
            if rows_data:
                missing.append("%s.table" % key)
            continue
        trs = tbl.findall(W + "tr")
        template_row = trs[-1] if len(trs) >= 2 else None
        if template_row is None:
            continue
        for extra in trs[2:-1]:
            tbl.remove(extra)
        row = template_row
        for item in rows_data:
            cells = effective_cells(row)
            if len(cells) >= 4:
                fill_cell(cells[0], item.get("name", ""))
                fill_cell(cells[1], item.get("role", ""))
                # cells[2] = signature cell: left blank for wet signature
                fill_cell(cells[3], item.get("date", ""))
            filled.append("%s.row" % key)
            if item is not rows_data[-1]:
                row = clone_row(tbl, row)

    # ---- approval date default ----
    approval = data.get("approval") if isinstance(data.get("approval"),
                                                  dict) else {}
    if approval:
        tbl = tail_tables.get("approval")
        if tbl is not None:
            trs = tbl.findall(W + "tr")
            if len(trs) >= 2:
                cells = effective_cells(trs[1])
                if len(cells) >= 4:
                    if approval.get("name"):
                        fill_cell(cells[0], approval["name"])
                    if approval.get("role"):
                        fill_cell(cells[1], approval["role"])
                    if approval.get("date"):
                        fill_cell(cells[3], approval["date"])
                    filled.append("approval.details")

    # ---- approval conditions box (last SDT of the §15 heading scope) ----
    cond = approval.get("conditions")
    if cond:
        items = grab("Approval of Investigation Report")
        if not items:
            missing.append("approval.conditions")
        else:
            sdts = scope_sdts(items)
            if not sdts:
                missing.append("approval.conditions")
            else:
                lines = str(cond).split("\n")
                L.fill_sdt(sdts[-1], lines, multi=True)
                filled.append("approval.conditions")

    # ---- save ----
    # The Title cell SDT is data-bound to the core document property
    # dc:title; Word pulls the visible text from docProps/core.xml on open.
    # core.xml is patched by string replacement (not re-serialised) because
    # xsi:type attribute values embed the "dcterms" QName prefix, which an
    # ElementTree round-trip would fail to redeclare.
    core = parts.get("docProps/core.xml")
    if core is not None and inc.get("title"):
        txt = core.decode("utf-8")
        safe = (str(inc["title"]).replace("&", "&amp;")
                .replace("<", "&lt;").replace(">", "&gt;"))
        txt, n = re.subn(r"<dc:title\s*/>|<dc:title>.*?</dc:title>",
                         "<dc:title>%s</dc:title>" % safe, txt, count=1)
        if n:
            parts["docProps/core.xml"] = txt.encode("utf-8")
            filled.append("docProps.title")
    L.strip_resolved_placeholders(doc)
    parts["word/document.xml"] = L.serialise_preserving_root(doc,
                                                             original_doc_bytes)
    L.save_parts(parts, out_path)

    if audit:
        print(json.dumps({"filled": sorted(set(filled)),
                          "missing": sorted(set(missing)),
                          "out": os.path.abspath(out_path)}, indent=1))
    else:
        print(json.dumps({"written": os.path.abspath(out_path),
                          "filled": len(set(filled)),
                          "missing": sorted(set(missing))}))
    return 0


import xml.etree.ElementTree as ET  # noqa: E402  (used by helpers above)

if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except SystemExit:
        raise
    except Exception as e:
        sys.stderr.write("build_report: unexpected failure: %r\n" % e)
        sys.exit(1)
